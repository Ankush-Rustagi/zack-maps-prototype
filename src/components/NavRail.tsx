// Map a target state to the rail button that should appear "active".
const RAIL_HIGHLIGHT: Partial<Record<StateId, StateId>> = {
  C: 'C',
  D: 'D',
  E: 'E',
  O: 'E', // collection detail keeps Collections lit
  F: 'F',
  L: 'F', // file dropzone keeps Files lit
  P: 'P',
};

export function NavRail() {
  const curState = useStore((s) => s.curState);
  const goState = useStore((s) => s.goState);
  const topBarVisible = useStore((s) => s.topBarVisible);
  const isEditor = curState === 'I';
  if (isEditor) return null;
  const activeId = RAIL_HIGHLIGHT[curState];

  return (
    <div className="nav-rail">
      {!topBarVisible && (
        <div className="rail-waffle" title="Verkada Command">
          {Array.from({ length: 9 }).map((_, i) => <span key={i} />)}
        </div>
      )}
      {RAIL_BTNS.map((b) => (
        <button
          key={b.id}
          className={`rail-btn${activeId === b.id ? ' active' : ''}`}
          onClick={() => goState(b.id)}
        >
          {b.icon}
          {b.label}
        </button>
      ))}
    </div>
  );
}
